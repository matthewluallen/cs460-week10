#!/usr/bin/env python3
"""Generate firmware constants/tags from the versioned public semantic map."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def generate(data):
    assert data['schema'] in ('tbd.plc-point-map/v2', 'tbd.plc-point-map/v3')
    assert data['schema'].endswith('/v' + str(data['version']))
    assert type(data['version']) is int and 1 <= data['version'] <= 65535
    points = data['points']; by_name = {}; occupied = set()
    for p in points:
        assert re.fullmatch('[a-z][a-z0-9_]*', p['name']) and p['name'] not in by_name
        assert p['kind'] in ('COIL', 'DI', 'REG') and p['encoding'] in ('u16', 's16')
        assert type(p['address']) is int and 0 <= p['address'] < {'COIL': data['coil_capacity'], 'REG': data['register_capacity'], 'DI': 8}[p['kind']]
        key = (p['kind'], p['address']); assert key not in occupied; occupied.add(key)
        assert type(p['operator_writable']) is bool and type(p['forceable']) is bool
        for key in ('unit', 'description'):
            assert type(p[key]) is str and len(p[key]) <= 180 and all(32 <= ord(c) < 127 for c in p[key])
            assert '"' not in p[key] and '\\' not in p[key], 'Current JSON views require literal-safe fixed descriptions'
        by_name[p['name']] = p
    digest_start = data['digest_registers']['start']
    assert data['digest_registers']['count'] == 16
    for i in range(digest_start, digest_start + 16):
        assert 0 <= i < data['register_capacity'] and ('REG', i) not in occupied
    for i in range(data['di_mirror_base'], data['di_mirror_base'] + 8):
        assert 0 <= i < data['coil_capacity'] and ('COIL', i) not in occupied
    vm = data['vm_inputs']; used = set(data['unbound_vm_words'])
    for v in data.get('bound_vm_words', []):
        assert type(v['index']) is int and v['index'] not in used
        assert re.fullmatch('[a-z][a-z0-9_]*', v['name'])
        used.add(v['index'])
    for v in vm:
        assert type(v['index']) is int and v['index'] not in used
        assert re.fullmatch('[a-z][a-z0-9_]*', v['name'])
        assert by_name[v['source']]['kind'] == 'REG'
        used.add(v['index'])
    assert used == set(range(data['vm_word_count']))
    defaults = data['parameter_defaults']; default_names = set()
    for d in defaults:
        p = by_name[d['point']]
        assert p['kind'] == 'REG' and p['operator_writable'] and d['point'] not in default_names
        assert type(d['value']) is int and (-32768 <= d['value'] <= 32767 if p['encoding'] == 's16' else 0 <= d['value'] <= 65535)
        default_names.add(d['point'])
    sha = hashlib.sha256(json.dumps(data, sort_keys=True, separators=(',', ':'), allow_nan=False).encode()).hexdigest()
    h = ['// Generated by scripts/generate_point_map.py; edit point_map.json.', '#pragma once', '#include <stdint.h>', 'namespace pointmap {',
         f'constexpr uint16_t VERSION = {data["version"]};', f'constexpr char SHA256[] = "{sha}";',
         f'constexpr uint16_t DIGEST_BASE = {digest_start};', f'constexpr uint16_t DI_MIRROR_BASE = {data["di_mirror_base"]};',
         f'constexpr int VM_WORD_COUNT = {data["vm_word_count"]};',
         'constexpr uint16_t DIGEST_WORDS[] = {' + ','.join('0x' + sha[i:i+4] for i in range(0,64,4)) + '};']
    h += [f'constexpr uint16_t {p["name"].upper()} = {p["address"]};' for p in points]
    h += [f'constexpr int IW_{v["name"].upper()} = {v["index"]};' for v in vm + data.get('bound_vm_words', [])]
    h += ['struct ParameterDefault { uint16_t address, value; };', 'constexpr ParameterDefault PARAMETERS[] = {']
    h += ['    {' + d['point'].upper() + ',' + str(d['value'] & 65535) + '},' for d in defaults]
    h += ['};', 'struct Metric { const char* name; uint16_t address; bool coil, signed_value; };', 'constexpr Metric SPARKPLUG_METRICS[] = {']
    metric_names = set()
    for m in data['sparkplug_metrics']:
        assert type(m['name']) is str and re.fullmatch('[A-Za-z0-9/_]+',m['name']) and len(m['name']) < 24 and m['name'] not in metric_names
        metric_names.add(m['name']); p = by_name[m['point']]
        address = p['address'] + (data['di_mirror_base'] if p['kind'] == 'DI' else 0)
        h += ['    {' + json.dumps(m['name']) + f',{address},' + ('false' if p['kind'] == 'REG' else 'true') + ',' + ('true' if p['encoding'] == 's16' else 'false') + '},']
    assert len(metric_names) <= 15, 'Requalify payload capacity before adding metrics'
    h += ['};']
    if 'process_bindings' in data:
        b = data['process_bindings']
        # This reviewed wire format is bounded below the protocol scratch region.
        expected = dict(clock_register=59, config_generation_register=61, format_register=63,
                        slot_base=64, slot_count=3, slot_words=16, status_register=112,
                        count_register=113, digest_start=114, digest_words=16)
        assert all(type(b[k]) is int and b[k] == v for k, v in expected.items())
        assert [(x['offset'], x['words']) for x in b['slot_layout']] == [(0,2),(2,1),(3,1),(4,2),(6,2),(8,2),(10,2),(12,2),(14,2)]
        for address in range(59,130):
            assert ('REG', address) not in occupied and not digest_start <= address < digest_start+16
        for k,v in expected.items(): h += [f'constexpr uint16_t BINDING_{k.upper()} = {v};']
        fs=b['fields']; assert len(fs)==15
        assert len({f['id'] for f in fs})==len(fs) and len({f['name'] for f in fs})==len(fs)
        for f in fs:
            assert re.fullmatch('[A-Za-z][A-Za-z0-9]*',f['id']) and re.fullmatch('[a-z][a-z0-9_]*',f['name'])
            assert re.fullmatch('[A-Za-z_]+',f['unit']) and type(f['scale']) is int and 0 < f['scale'] <= 1000
            assert type(f['kind']) is int and 0 <= f['kind'] <= 5
        h += ['enum class ProcessField : uint8_t {' + ','.join(f['id'] for f in fs) + ',Count};',
              'struct ProcessFieldDef { const char* name; const char* unit; int scale; uint8_t kind; };',
              'constexpr ProcessFieldDef PROCESS_FIELDS[] = {']
        h += ['    {' + json.dumps(f['name']) + ',' + json.dumps(f['unit']) + f',{f["scale"]},{f["kind"]}' + '},' for f in fs]
        h += ['};']
    h += ['} // namespace pointmap']
    tags = ['// Generated by scripts/generate_point_map.py; edit point_map.json.']
    for p in points:
        tags += ['    {' + ', '.join([json.dumps(p['name']), 'TK_' + p['kind'], 'pointmap::' + p['name'].upper(), json.dumps(p['unit']), str(p['operator_writable']).lower(), str(p['forceable']).lower(), json.dumps(p['description']), str(p['encoding'] == 's16').lower()]) + '},']
    return {'plc_point_map.h': '\n'.join(h) + '\n', 'plc_point_tags.inc': '\n'.join(tags) + '\n'}


def run(check=False):
    outputs = generate(json.loads((ROOT / 'point_map.json').read_text()))
    for name, content in outputs.items():
        p = ROOT / 'src' / name
        if check:
            if not p.exists() or p.read_text() != content:
                raise SystemExit('stale generated point map: ' + str(p))
        else:
            p.write_text(content)


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    run(ap.parse_args().check)

#ifndef OPENPLC_RUNTIME_H
#define OPENPLC_RUNTIME_H

#include <Arduino.h>
#include "config.h"

// OpenPLC Runtime wrapper for ESP32/M5 StampLC
// Provides interface to OpenPLC interpreter and coil/register memory

class OpenPLCRuntime {
public:
    OpenPLCRuntime();
    bool init();
    void start();
    void stop();

    // Main scan cycle (call periodically)
    void scan_cycle();

    // Coil/register access
    void set_coil(uint16_t addr, bool state);
    bool get_coil(uint16_t addr);
    void set_register(uint16_t addr, uint16_t val);
    uint16_t get_register(uint16_t addr);

    // Program management
    bool load_program(const uint8_t* bytecode, size_t len);
    bool start_program();
    void stop_program();

    // Status
    uint32_t get_cycle_time_ms();
    bool is_running();

private:
    // OpenPLC memory
    uint16_t coils[512 / 16];           // Coils (bit-packed)
    uint16_t registers[512];            // Registers

    bool running;
    uint32_t last_cycle_time;
    uint32_t cycle_count;

    // Stub for actual OpenPLC interpreter
    // In production, this would call the MatIEC-generated bytecode
};

extern OpenPLCRuntime openplc_runtime;

#endif // OPENPLC_RUNTIME_H
